def build_bow(palette):
    """A curved limb and a string. The curve is the read."""
    parts = []
    radius = 0.52
    steps = 8
    half = math.radians(58.0)
    pts = []
    for i in range(steps + 1):
        t = -half + 2.0 * half * i / steps
        pts.append((0.0, math.cos(t) * radius, math.sin(t) * radius))
    for i in range(steps):
        a, b = pts[i], pts[i + 1]
        mid = ((a[0] + b[0]) * 0.5, (a[1] + b[1]) * 0.5, (a[2] + b[2]) * 0.5)
        delta = Vector((b[0] - a[0], b[1] - a[1], b[2] - a[2]))
        length = delta.length
        parts.append(add_cyl(f"limb_{i}", 0.022, length, mid, "leather", palette, verts=6,
                              rot=(math.atan2(delta.z, math.hypot(delta.x, delta.y)), 0.0,
                                   math.atan2(-delta.x, delta.y))))
    parts.append(add_cyl("string", 0.006, 2.0 * radius * math.sin(half), (0.0, 0.0, 0.0),
                          "cloth", palette, verts=4))
    return parts


