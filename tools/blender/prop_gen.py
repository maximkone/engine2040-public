def material(name, colour):
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (colour[0], colour[1], colour[2], 1.0)
    return mat


def add_box(name, size, loc, kind, palette, rot=(0.0, 0.0, 0.0), taper=1.0):
    bpy.ops.mesh.primitive_cube_add(size=1.0, location=loc)
    ob = bpy.context.object
    ob.name = name
    ob.scale = (size[0], size[1], size[2])
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    if taper != 1.0:
        for vertex in ob.data.vertices:
            if vertex.co.z < 0.0:
                vertex.co.x *= taper
                vertex.co.y *= taper
    ob.rotation_euler = rot
    ob.data.materials.append(material(f"{name}_mat", palette[kind]))
    return ob


def add_cyl(name, radius, depth, loc, kind, palette, rot=(0.0, 0.0, 0.0), verts=12):
    bpy.ops.mesh.primitive_cylinder_add(vertices=verts, radius=radius, depth=depth, location=loc)
    ob = bpy.context.object
    ob.name = name
    ob.rotation_euler = rot
    ob.data.materials.append(material(f"{name}_mat", palette[kind]))
    return ob


def add_cone(name, radius, depth, loc, kind, palette, rot=(0.0, 0.0, 0.0), verts=12):
    bpy.ops.mesh.primitive_cone_add(vertices=verts, radius1=radius, radius2=0.0, depth=depth, location=loc)
    ob = bpy.context.object
    ob.name = name
    ob.rotation_euler = rot
    ob.data.materials.append(material(f"{name}_mat", palette[kind]))
    return ob


def add_sphere(name, radius, loc, kind, palette, scale=(1.0, 1.0, 1.0), verts=12):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=verts, ring_count=verts // 2, radius=radius, location=loc)
    ob = bpy.context.object
    ob.name = name
    ob.scale = scale
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    ob.data.materials.append(material(f"{name}_mat", palette[kind]))
    return ob


def add_torus(name, major, minor, loc, kind, palette, rot=(0.0, 0.0, 0.0)):
    bpy.ops.mesh.primitive_torus_add(major_radius=major, minor_radius=minor, location=loc)
    ob = bpy.context.object
    ob.name = name
    ob.rotation_euler = rot
    ob.data.materials.append(material(f"{name}_mat", palette[kind]))
    return ob


