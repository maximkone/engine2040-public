def build_mace(palette):
    parts = []
    parts.append(add_cyl("haft", 0.032, 0.85, (0.0, 0.0, 0.0), "leather", palette, verts=8))
    parts.append(add_sphere("head", 0.115, (0.0, 0.0, 0.48), "iron", palette))
