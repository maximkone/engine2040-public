    parts.append(add_box("guard", (0.30 if heavy else 0.20, 0.06, 0.05), (0.0, 0.0, 0.10), "bronze", palette))
    parts.append(add_cyl("grip", 0.028, 0.22, (0.0, 0.0, -0.03), "leather", palette, verts=8))
    parts.append(add_sphere("pommel", 0.045, (0.0, 0.0, -0.16), "bronze", palette))
    return parts


