def build(prop, palette, reset=True):
    key = prop.get("build")
    builder = BUILDERS.get(key)
    if builder is None:
        raise PropError(f"{prop['id']}: no builder named {key}")
    if reset:
        bpy.ops.wm.read_factory_settings(use_empty=True)
    parts = builder(palette)
    bpy.ops.object.select_all(action="DESELECT")
    for ob in parts:
        ob.select_set(True)
    bpy.context.view_layer.objects.active = parts[0]
    if len(parts) > 1:
        bpy.ops.object.join()
    ob = bpy.context.view_layer.objects.active
    ob.name = prop["id"]
    scale = float(prop.get("scale", 1.0))
    if scale != 1.0:
        ob.scale = (scale, scale, scale)
    bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
    # Flat shaded: the old look had hard faces, not smooth ones.
    for polygon in ob.data.polygons:
        polygon.use_smooth = False
    return ob


def rack(data, path):
    """Every prop on one sheet, so a weapon can be judged against the others.

    A weapon that only looks good alone is not a weapon: the read has to
    hold next to a shield and a staff.
    """
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.render.engine = "BLENDER_WORKBENCH"
    scene.render.resolution_x = 1800
    scene.render.resolution_y = 1200
    scene.render.resolution_percentage = 100
    scene.render.film_transparent = False
    scene.render.image_settings.file_format = "PNG"
    scene.display.shading.light = "STUDIO"
    scene.display.shading.color_type = "MATERIAL"
    scene.display.shading.show_shadows = True
    try:
        scene.view_settings.view_transform = "Standard"
    except Exception:
        pass
    world = bpy.data.worlds.new("rack_world")
    scene.world = world
    world.color = (0.16, 0.15, 0.14)
    try:
        with __import__("warnings").catch_warnings():
            __import__("warnings").simplefilter("ignore", DeprecationWarning)
            if getattr(world, "node_tree", None) is None and hasattr(world, "use_nodes"):
                world.use_nodes = True
        tree = getattr(world, "node_tree", None)
        if tree:
            node = tree.nodes.get("Background")
            if node:
                node.inputs[0].default_value = (0.16, 0.15, 0.14, 1.0)
    except Exception:
        pass
    scene.display.shading.background_type = "WORLD"

    props = data.get("props", [])
    columns = 8
    cell_x, cell_y = 1.35, 1.75
    for index, prop in enumerate(props):
        palette = FACTION_PALETTE.get(prop.get("faction", "neutral"), NEUTRAL)
        ob = build(prop, palette, reset=False)
        bpy.ops.object.select_all(action="DESELECT")
        ob.select_set(True)
        bpy.context.view_layer.objects.active = ob
        bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
        # Stand it on the shelf: the builder already put the grip at the
        # origin, so only the height needs lifting.
        low = Vector((1e9, 1e9, 1e9))
        high = Vector((-1e9, -1e9, -1e9))
        for vertex in ob.data.vertices:
            for i in range(3):
                low[i] = min(low[i], vertex.co[i])
                high[i] = max(high[i], vertex.co[i])
        column = index % columns
        row = index // columns
        target_x = (column - (columns - 1) / 2.0) * cell_x
        target_y = -row * cell_y
        ob.location = (target_x - (low.x + high.x) * 0.5, target_y - (low.y + high.y) * 0.5, -low.z + 0.02)
        name = prop["id"].replace("warden_", "").replace("ashkin_", "").replace("world_", "")
        curve = bpy.data.curves.new(f"label_{prop['id']}", type="FONT")
        curve.body = name.replace("_", " ")
        curve.size = 0.115
        curve.align_x = "CENTER"
        text = bpy.data.objects.new(f"label_{prop['id']}", curve)
        bpy.context.collection.objects.link(text)
        text.location = (target_x, target_y - 0.62, 0.02)
        text.rotation_euler = (0.0, 0.0, 0.0)
        mat = bpy.data.materials.new("label_mat")
        mat.diffuse_color = (0.85, 0.80, 0.70, 1.0)
        text.data.materials.append(mat)

    rows = (len(props) + columns - 1) // columns
    cam_data = bpy.data.cameras.new("rack_cam")
    cam_data.type = "ORTHO"
    width = columns * cell_x * 1.02
    cam_data.ortho_scale = width
    cam = bpy.data.objects.new("rack_cam", cam_data)
    bpy.context.collection.objects.link(cam)
    # Three quarters from the front and a little above: a weapon is read in
    # profile, and a top-down view turns a sword into a line.
    centre_y = -(rows - 1) * cell_y * 0.5
    cam.location = (0.0, centre_y - 11.5, 7.5)
    cam.rotation_euler = (math.radians(58.0), 0.0, 0.0)
    scene.camera = cam

    scene.render.filepath = path
    bpy.ops.render.render(write_still=True)
    return path


def main():
    args = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    if not args:
        sys.stderr.write("usage: blender -b --factory-startup --python-exit-code 1 "
                         "-P prop_gen.py -- <outdir> [--only <id>]\n")
        return EXIT_USAGE
    outdir = args[0]
    only = None
    if "--only" in args:
        only = args[args.index("--only") + 1]

    data = catalogue()
    os.makedirs(outdir, exist_ok=True)
    written = []
    for prop in data.get("props", []):
        if only and prop["id"] != only:
            continue
        palette = FACTION_PALETTE.get(prop.get("faction", "neutral"), NEUTRAL)
        ob = build(prop, palette)
        path = os.path.join(outdir, f"{prop['id']}.glb")
        try:
            bpy.ops.export_scene.gltf(filepath=path, export_format="GLB", export_apply=True,
                                      export_texcoords=True, export_normals=True,
                                      use_selection=True)
        except TypeError:
            bpy.ops.export_scene.gltf(filepath=path, export_format="GLB")
        if not os.path.exists(path) or os.path.getsize(path) == 0:
            raise PropError(f"could not write {path}")
        triangles = 0
        for polygon in ob.data.polygons:
            triangles += max(0, len(polygon.vertices) - 2)
        written.append({"id": prop["id"], "file": os.path.basename(path),
                        "triangles": triangles, "build": prop.get("build"),
                        "classes": prop.get("classes", [])})
        print(f"PROP {prop['id']} {triangles} tris")

    with open(os.path.join(outdir, "props_built.json"), "w", encoding="utf-8") as handle:
        json.dump({"count": len(written), "props": written}, handle, indent=2, sort_keys=True)
    rack_path = os.path.join(outdir, "prop_rack.png")
    try:
        rack(data, rack_path)
        print(f"RACK {rack_path}")
    except Exception as err:
        print(f"RACK FAILED {type(err).__name__}: {err}")
    print(json.dumps({"count": len(written)}, sort_keys=True))
    return 0


if __name__ == "__main__":
    try:
        code = main()
    except PropError as err:
        sys.stderr.write(f"E_PROP {err}\n")
        code = EXIT_FAIL
    except Exception as err:
        sys.stderr.write(f"E_PROP {type(err).__name__}: {err}\n")
        code = EXIT_FAIL
    if code != 0:
        sys.exit(code)
