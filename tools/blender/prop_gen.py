"""The prop generator: our weapons, armour and world props.

The 2005 look was never about triangle count. It was about a handful of
strong shapes: a greatsword that reads at thirty metres, a cannon that
says "artillery" from across a map, a pauldron that says "faction". A
texture cannot do that. A silhouette can.

So the weapons are ours, built from primitives, in the faction palette, with
one material per surface kind (iron, bronze, bone, cloth, leather, ember)
so the engine's two roughness values have something to work with. Nothing
here is generated by a model: the shapes are authored, so they are the same
on every machine and they cost nothing to make.

The catalogue in content/design/props.json says which prop belongs to which
class and which builder makes it. This file is the builders.

Run:
  blender -b --factory-startup --python-exit-code 1 -P tools/blender/prop_gen.py -- <outdir> [--only <id>]
"""

