// Faction war campaign report: run the class validator, block out every
// archetype through the Blender generator, and write one report file.
//
// Run: node tools/faction-war-report.mjs
// Writes: docs/research/faction-war-2026-10-21/art-report.md
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BLENDER = "C:\\Program Files\\Blender Foundation\\Blender 5.2\\blender.exe";
const SPEC_DIR = join(ROOT, "content", "design", "blockout");
const OUT_DIR = join(ROOT, "docs", "research", "faction-war-2026-10-21");
const FRAMES = join(process.env.TEMP || "C:\\Users\\me\\AppData\\Local\\Temp", "opencode", "faction-war-frames");

const lines = [];
const note = (s) => { lines.push(s); console.log(s); };

note("# Faction war campaign report");
note("");
note("Generated by `node tools/faction-war-report.mjs`.");

// ---- 1. class validator ----------------------------------------------------
note("## Class data");
const validator = join(ROOT, "tools", "class-validate.mjs");
if (existsSync(validator)) {
  try {
    const out = execFileSync(process.execPath, [validator], { cwd: ROOT, encoding: "utf8" });
    note("Validator output:");
    note("");
    note("```");
    note(out.trim());
    note("```");
  } catch (err) {
    note("Validator output (non-zero exit):");
    note("");
    note("```");
    note((err.stdout || "").toString().trim());
    note((err.stderr || "").toString().trim());
    note("```");
  }
} else {
  note("Validator not present yet: `tools/class-validate.mjs`.");
}

// ---- 2. archetype blockouts ------------------------------------------------
note("");
note("## Archetype blockouts");
const specs = existsSync(SPEC_DIR)
  ? readdirSync(SPEC_DIR).filter((n) => n.endsWith(".json")).sort()
  : [];
if (!specs.length) {
  note("No archetype specs found.");
} else if (!existsSync(join(ROOT, "tools", "blender", "blockout.py"))) {
  note("Generator not present yet: `tools/blender/blockout.py`.");
} else {
  mkdirSync(FRAMES, { recursive: true });
  for (const spec of specs) {
    const name = spec.replace(/\.json$/, "");
    const dest = join(FRAMES, name);
    try {
      const out = execFileSync(BLENDER, [
        "-b", "--factory-startup", "--python-exit-code", "1",
        "-P", join(ROOT, "tools", "blender", "blockout.py"),
        "--", join(SPEC_DIR, spec), dest,
      ], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], timeout: 300000 });
      const metric = out.split(/\r?\n/).find((l) => {
        const t = l.trim();
        if (!t.startsWith("{")) return false;
        try { return typeof JSON.parse(t) === "object"; } catch { return false; }
      });
      note(`- **${name}**`);
      if (metric) note(`  - metrics: ${metric.trim()}`);
      for (const png of ["silhouette_big.png", "silhouette_30m.png", "grey_studio.png"]) {
        const p = join(dest, png);
        note(`  - ${png}: ${existsSync(p) ? "ok" : "MISSING"}`);
      }
    } catch (err) {
      note(`- **${name}** FAILED: ${(err.stderr || err.message || "").toString().split(/\r?\n/).slice(-3).join(" ")}`);
    }
  }
}

note("");
note("## Verdict");
note("");
note("A silhouette passes when it reads at 90 pixels tall: faction first, class second, nothing that only a texture can explain.");

mkdirSync(OUT_DIR, { recursive: true });
const path = join(OUT_DIR, "art-report.md");
writeFileSync(path, lines.join("\n") + "\n", "utf8");
console.log("WROTE " + path);
