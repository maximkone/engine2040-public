//! MCP9 declarative tools and test harvest: `e2_tool!` plus `test.run`.
//!
//! Consumer: external MCP clients and the EV1 eval harness through the
//! endpoint router. Data owner stays the editor command service; this module
//! owns only the tool generator and the read-only harvest runner. Units are
//! chars for budgets and counts for cases. Determinism scope: case order is
//! request order, details carry numbers only, no wall clock, no threads.
//! Errors are [`McpToolError`] codes that always name the legal values.
//! Budgets: at most [`MAX_TEST_RUN_CHECKS`] cases per run, details capped by
//! `budget_bytes` (default [`TEST_RUN_DEFAULT_BUDGET`], hard
//! [`TEST_RUN_MAX_BUDGET`]).
//!
//! The `#[e2_tool]` attribute from the board is realized as the declarative
//! `e2_tool!` macro below (same expansion a proc-macro would emit: one
//! `ToolBase` plus one `SyncTool<McpServer>` over a typed handler fn). A
//! true attribute spelling needs a new proc-macro crate plus a manifest row,
//! which this lane may not add (`--locked`); that extraction is orchestrator
//! follow-up. `test.run` itself is generated by the macro and served through
//! its own router in tests; main-router registration would make the door
//! nineteen tools and is deferred with its budget rebump.

