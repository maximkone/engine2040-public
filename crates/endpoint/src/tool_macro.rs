/// Tool name for the structured harvest runner.
pub const TOOL_TEST_RUN: &str = "test.run";
/// Default `test.run` detail budget in chars.
pub const TEST_RUN_DEFAULT_BUDGET: u32 = 4096;
/// Hard `test.run` detail budget in chars.
pub const TEST_RUN_MAX_BUDGET: u32 = 16_384;
/// Most cases one `test.run` call may request.
pub const MAX_TEST_RUN_CHECKS: usize = 16;

/// Harvest checks every `test.run` call may name, in default run order.
/// Anything else is refused with this list attached (default deny, never an
/// open set: the runner executes no arbitrary code).
pub const TEST_RUN_CHECKS: &[&str] = &[
    "scene_read",
    "tx_preview",
    "tool_budget",
    "discover",
    "log_digest",
];

/// Args for `test.run`: which harvest checks to run, bounded.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq, Eq, Default)]
#[serde(crate = "rmcp::serde")]
#[schemars(crate = "rmcp::schemars")]
pub struct TestRunArgs {
    pub checks: Option<Vec<String>>,
    pub budget_bytes: Option<u32>,
}

/// One harvest case result: the check name, pass/fail and numbers an agent
/// can act on (revision, totals, chars of budget).
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq, Eq)]
#[serde(crate = "rmcp::serde")]
#[schemars(crate = "rmcp::schemars")]
pub struct TestCaseResult {
    pub name: String,
    pub ok: bool,
    pub detail: String,
}

/// `test.run` result: envelope revision plus one structured row per case in
/// request order. `truncated` means the detail budget cut trailing cases.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq, Eq, Default)]
#[serde(crate = "rmcp::serde")]
#[schemars(crate = "rmcp::schemars")]
pub struct TestRunOutput {
    pub revision: u64,
    pub passed: u64,
    pub failed: u64,
    pub truncated: bool,
    pub results: Vec<TestCaseResult>,
}

/// Refusal for an unknown check name: names the legal set.
fn unknown_check(name: &str) -> McpToolError {
    McpToolError::new(
        "unknown_check",
        format!(
            "check `{name}` is unknown; legal checks: [{}]",
            TEST_RUN_CHECKS.join(", ")
        ),
    )
}

/// A failed case still answers structured: `ok` false with the error code
/// and message an agent can act on.
fn case_failed(name: &str, error: &McpToolError) -> TestCaseResult {
    TestCaseResult {
        name: name.to_owned(),
        ok: false,
        detail: format!("{name} failed {error}"),
    }
}

/// Current document revision for the envelope (read-only scene read).
fn envelope_revision(server: &McpServer) -> Result<u64, McpToolError> {
    SceneReadTool::invoke(
        server,
        SceneReadArgs {
            limit: Some(1),
            cursor: Some(0),
        },
    )
    .map(|page| page.revision)
}

/// One harvest case against the live server. All five are read-only:
/// `tx_preview` dry-runs a synthetic insert (no side effects by the preview
/// contract), the rest are pure reads.
fn run_one(server: &McpServer, name: &str) -> TestCaseResult {
    let ok = |detail: String| TestCaseResult {
        name: name.to_owned(),
        ok: true,
        detail,
    };
    match name {
        "scene_read" => match SceneReadTool::invoke(
            server,
            SceneReadArgs {
                limit: Some(1),
                cursor: Some(0),
            },
        ) {
            Ok(page) => ok(format!(
                "revision {} total {} (paged limit 1)",
                page.revision, page.total
            )),
            Err(error) => case_failed(name, &error),
        },
        "tx_preview" => {
            let revision = match envelope_revision(server) {
                Ok(revision) => revision,
                Err(error) => return case_failed(name, &error),
            };
            let ops = vec![OpDto::Insert {
                id: ObjectId::new().to_string(),
                parent: ObjectId::NIL.to_string(),
                local: PoseDto {
                    pos: [1.0, 0.0, 0.0],
                    rot: [0.0, 0.0, 0.0, 1.0],
                    scale: [1.0, 1.0, 1.0],
                },
            }];
            match TxPreviewTool::invoke(
                server,
                TxPreviewArgs {
                    expected_revision: revision,
                    idempotency_key: u64::MAX - 2040,
                    ops,
                },
            ) {
                // No hash or id in the detail: the synthetic insert mints a
                // fresh random id every run, so only counts and revisions
                // (deterministic) may ride the structured result.
                Ok(preview) => ok(format!(
                    "dry-run {} effects revision {} (wrote nothing)",
                    preview.effects.len(),
                    preview.resulting_revision
                )),
                Err(error) => case_failed(name, &error),
            }
        }
        "tool_budget" => {
            let chars = server.tool_list_budget_chars();
            if chars <= TOOL_LIST_BUDGET_CHARS {
                ok(format!(
                    "list costs {chars} chars of {TOOL_LIST_BUDGET_CHARS}"
                ))
            } else {
                case_failed(
                    name,
                    &McpToolError::new(
                        "over_budget",
                        format!("list costs {chars} chars, budget is {TOOL_LIST_BUDGET_CHARS}"),
                    ),
                )
            }
        }
        "discover" => {
            let manifest = DiscoverManifest::from_server(server, false);
            ok(format!(
                "manifest holds {} tools costing {} chars (hidden omitted {})",
                manifest.tool_count(),
                manifest.manifest_chars(),
                manifest.hidden_omitted
            ))
        }
        "log_digest" => match LogDigestTool::invoke(server, LogDigestArgs { budget_bytes: None }) {
            Ok(digested) => ok(format!(
                "ring holds {} events overflowing {} ({} bytes)",
                digested.events, digested.overflow, digested.bytes
            )),
            Err(error) => case_failed(name, &error),
        },
        _ => case_failed(name, &unknown_check(name)),
    }
}

/// Resolve the requested check list: `None` runs every known check in
/// contract order; an explicit list validates each name (default deny) and
/// refuses empty or over-long lists with the legal values attached.
fn resolve_checks(args: &TestRunArgs) -> Result<Vec<String>, McpToolError> {
    match &args.checks {
        None => Ok(TEST_RUN_CHECKS.iter().map(ToString::to_string).collect()),
        Some(wanted) => {
            if wanted.is_empty() {
                return Err(McpToolError::new(
                    "empty_checks",
                    format!(
                        "checks holds 0 entries; submit 1..={MAX_TEST_RUN_CHECKS} of [{}]",
                        TEST_RUN_CHECKS.join(", ")
                    ),
                ));
            }
            if wanted.len() > MAX_TEST_RUN_CHECKS {
                return Err(McpToolError::new(
                    "too_many_checks",
                    format!(
                        "checks holds {} entries; at most {MAX_TEST_RUN_CHECKS} per run",
                        wanted.len()
                    ),
                ));
            }
            for name in wanted {
                if !TEST_RUN_CHECKS.contains(&name.as_str()) {
                    return Err(unknown_check(name));
                }
            }
            Ok(wanted.clone())
        }
    }
}

/// Run the harvest: envelope revision plus one structured row per case in
/// request order. Detail chars beyond `budget_bytes` cut trailing cases and
/// set `truncated`. Writes nothing: every case is a pure read or a dry-run
/// preview.
pub fn run_checks(server: &McpServer, args: &TestRunArgs) -> Result<TestRunOutput, McpToolError> {
    let budget = args.budget_bytes.unwrap_or(TEST_RUN_DEFAULT_BUDGET);
    if budget == 0 || budget > TEST_RUN_MAX_BUDGET {
        return Err(McpToolError::new(
            "bad_budget",
            format!(
                "budget_bytes {budget} is outside 1..={TEST_RUN_MAX_BUDGET} \
                 (default {TEST_RUN_DEFAULT_BUDGET})"
            ),
        ));
    }
    let wanted = resolve_checks(args)?;
    let revision = envelope_revision(server)?;
    let mut results = Vec::with_capacity(wanted.len());
    let mut spent = 0usize;
    let mut truncated = false;
    for name in &wanted {
        let result = run_one(server, name);
        spent += result.detail.len();
        if spent > budget as usize {
            truncated = true;
            break;
        }
        results.push(result);
    }
    let passed = results.iter().filter(|row| row.ok).count() as u64;
    let failed = results.len() as u64 - passed;
    Ok(TestRunOutput {
        revision,
        passed,
        failed,
        truncated,
        results,
    })
}

crate::e2_tool!(
    /// `test.run` tool: structured harvest results agents can act on. Read-only.
    TestRunTool,
    name = TOOL_TEST_RUN,
    description = "Run the structured harvest checks (scene, preview, budget, manifest, log) with no side effects. Read-only.",
    readonly = true,
    args = TestRunArgs,
    output = TestRunOutput,
    invoke = run_checks
);

#[cfg(test)]
mod tests {
    use super::super::discover::RpcError;
    use super::*;
    use engine_editor::capability::Capability;
    use rmcp::handler::server::router::tool::{SyncTool, ToolBase, ToolRouter};

    fn test_server() -> McpServer {
        McpServer::new(7, Capability::unrestricted(7))
    }

    // -- Example typed fn for the factory -----------------------------------

    /// Typed failure for the echo example: maps onto the one wire shape.
    #[derive(Debug, Clone, PartialEq, Eq)]
    enum PingError {
        EmptyWord,
    }

    impl std::fmt::Display for PingError {
        fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
            match self {
                Self::EmptyWord => write!(f, "word is empty; submit one non-empty word"),
            }
        }
    }

    impl From<PingError> for McpToolError {
        fn from(error: PingError) -> Self {
            McpToolError::new("bad_word", error.to_string())
        }
    }

    #[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq, Eq, Default)]
    #[serde(crate = "rmcp::serde")]
    #[schemars(crate = "rmcp::schemars")]
    pub struct PingArgs {
        word: String,
    }

    #[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, PartialEq, Eq, Default)]
    #[serde(crate = "rmcp::serde")]
    #[schemars(crate = "rmcp::schemars")]
    pub struct PingOutput {
        echo: String,
    }

    fn ping_impl(_server: &McpServer, args: &PingArgs) -> Result<PingOutput, McpToolError> {
        if args.word.is_empty() {
            return Err(PingError::EmptyWord.into());
        }
        Ok(PingOutput {
            echo: format!("pong {}", args.word),
        })
    }

    crate::e2_tool!(
        MacroPingTool,
        name = "ping.macro",
        description = "Echo one word through the generated tool. Read-only.",
        readonly = true,
        args = PingArgs,
        output = PingOutput,
        invoke = ping_impl
    );

    /// Hand-written twin of the generated tool: same handler, manual impls.
    struct ManualPingTool;

    impl ToolBase for ManualPingTool {
        type Parameter = PingArgs;
        type Output = PingOutput;
        type Error = McpToolError;

        fn name() -> std::borrow::Cow<'static, str> {
            "ping.macro".into()
        }

        fn description() -> Option<std::borrow::Cow<'static, str>> {
            Some("Echo one word through the generated tool. Read-only.".into())
        }

        fn annotations() -> Option<rmcp::model::ToolAnnotations> {
            let mut annotations = rmcp::model::ToolAnnotations::default();
            annotations.read_only_hint = Some(true);
            annotations.open_world_hint = Some(false);
            Some(annotations)
        }
    }

    impl SyncTool<McpServer> for ManualPingTool {
        fn invoke(
            service: &McpServer,
            param: Self::Parameter,
        ) -> Result<Self::Output, Self::Error> {
            ping_impl(service, &param)
        }
    }

    fn ping_args(word: &str) -> PingArgs {
        PingArgs {
            word: word.to_owned(),
        }
    }

    /// EV1 acceptance, factory level: the suite run through generated tools
    /// equals the suite run through hand-written tools, so the harness
    /// cannot tell them apart.
    #[test]
    fn generated_tools_equal_hand_written() {
        let server = test_server();
        let args = ping_args("arena");
        let from_macro =
            MacroPingTool::invoke(&server, args.clone()).expect("generated tool serves");
        let manual = ManualPingTool::invoke(&server, args).expect("manual tool serves");
        assert_eq!(from_macro, manual, "generated equals hand-written");
        assert_eq!(from_macro.echo, "pong arena");
        // Same registration shape: name, readonly flag and both schemas.
        assert_eq!(MacroPingTool::name(), ManualPingTool::name());
        assert_eq!(
            MacroPingTool::annotations().expect("annotations ride along"),
            ManualPingTool::annotations().expect("annotations ride along")
        );
        let macro_input = rmcp::serde_json::to_string(&MacroPingTool::input_schema())
            .expect("input schema serializes");
        let manual_input = rmcp::serde_json::to_string(&ManualPingTool::input_schema())
            .expect("input schema serializes");
        assert_eq!(macro_input, manual_input, "input schemas match");
        assert!(
            macro_input.contains("word"),
            "schema names its field: {macro_input}"
        );
        let macro_output = rmcp::serde_json::to_string(&MacroPingTool::output_schema())
            .expect("output schema serializes");
        let manual_output = rmcp::serde_json::to_string(&ManualPingTool::output_schema())
            .expect("output schema serializes");
        assert_eq!(macro_output, manual_output, "output schemas match");
        // Same errors: the typed refusal converts to the one wire shape.
        let refused = MacroPingTool::invoke(&server, ping_args("")).expect_err("empty refuses");
        assert_eq!(refused.code, "bad_word");
        assert!(refused.message.contains("non-empty"));
        let manual_refused =
            ManualPingTool::invoke(&server, ping_args("")).expect_err("empty refuses");
        assert_eq!(refused.to_string(), manual_refused.to_string());
        // Twice: the same inputs give the same outputs.
        assert_eq!(
            MacroPingTool::invoke(&server, ping_args("arena")).expect("repeats"),
            from_macro
        );
    }

    /// Generated tools register on a router with schema and errors: the
    /// factory output is a real MCP tool, not a local helper.
    #[test]
    fn generated_tools_register_with_schema_and_errors() {
        let router = ToolRouter::<McpServer>::new()
            .with_sync_tool::<MacroPingTool>()
            .with_sync_tool::<TestRunTool>();
        let names: Vec<String> = router
            .list_all()
            .iter()
            .map(|tool| tool.name.to_string())
            .collect();
        assert!(names.contains(&"ping.macro".to_owned()), "ping registers");
        assert!(
            names.contains(&TOOL_TEST_RUN.to_owned()),
            "test.run registers"
        );
        for tool in router.list_all() {
            assert!(
                !tool.input_schema.is_empty(),
                "tool `{}` advertises its input schema",
                tool.name
            );
            assert!(
                tool.output_schema.is_some(),
                "tool `{}` advertises its output schema",
                tool.name
            );
        }
        let ping = router
            .list_all()
            .iter()
            .find(|tool| tool.name == "ping.macro")
            .expect("ping is listed")
            .clone();
        assert_eq!(
            ping.annotations
                .as_ref()
                .and_then(|annotations| annotations.read_only_hint),
            Some(true),
            "readonly rides the annotations"
        );
        // The one error shape carries the refusal across the door.
        let server = test_server();
        let refused = TestRunTool::invoke(
            &server,
            TestRunArgs {
                checks: Some(vec!["exec".to_owned()]),
                budget_bytes: None,
            },
        )
        .expect_err("unknown check refuses");
        assert_eq!(refused.code, "unknown_check");
        let wire = RpcError::from(refused);
        assert_eq!(wire.code(), "unknown_check");
        assert!(wire.message.contains("scene_read"));
    }

    /// `test.run` returns structured results agents can act on: one row per
    /// case in request order, repeatable, writing nothing.
    #[test]
    fn test_run_structured_deterministic_and_readonly() {
        let server = test_server();
        let revision = envelope_revision(&server).expect("envelope reads");
        let full = TestRunTool::invoke(
            &server,
            TestRunArgs {
                checks: None,
                budget_bytes: None,
            },
        )
        .expect("full harvest serves");
        assert_eq!(full.revision, revision);
        assert_eq!(full.results.len(), TEST_RUN_CHECKS.len());
        let names: Vec<&str> = full.results.iter().map(|row| row.name.as_str()).collect();
        assert_eq!(names, TEST_RUN_CHECKS);
        assert_eq!(full.passed, TEST_RUN_CHECKS.len() as u64);
        assert_eq!(full.failed, 0);
        assert!(!full.truncated);
        for row in &full.results {
            assert!(
                !row.detail.is_empty(),
                "case `{}` reports numbers",
                row.name
            );
        }
        let budget_row = full
            .results
            .iter()
            .find(|row| row.name == "tool_budget")
            .expect("budget case runs");
        assert!(
            budget_row
                .detail
                .contains(&TOOL_LIST_BUDGET_CHARS.to_string()),
            "budget case names its bound: {}",
            budget_row.detail
        );
        // A filtered run keeps request order with the same rows.
        let filtered = TestRunTool::invoke(
            &server,
            TestRunArgs {
                checks: Some(vec!["log_digest".to_owned(), "scene_read".to_owned()]),
                budget_bytes: None,
            },
        )
        .expect("filtered harvest serves");
        assert_eq!(filtered.results.len(), 2);
        assert_eq!(filtered.results[0].name, "log_digest");
        assert_eq!(filtered.results[1].name, "scene_read");
        assert_eq!(
            filtered.results[0], full.results[4],
            "rows match the full run"
        );
        assert_eq!(
            filtered.results[1], full.results[0],
            "rows match the full run"
        );
        // Twice: the same harvest gives the same structured results, and the
        // document never moved (every case reads or dry-runs).
        let again = run_checks(
            &server,
            &TestRunArgs {
                checks: None,
                budget_bytes: None,
            },
        )
        .expect("harvest repeats");
        assert_eq!(again, full, "generated equals direct, twice");
        assert_eq!(
            envelope_revision(&server).expect("envelope re-reads"),
            revision,
            "the harvest writes nothing"
        );
    }

    /// `test.run` refuses bad input with the legal values attached, and the
    /// detail budget cuts trailing cases instead of overflowing.
    #[test]
    fn test_run_refuses_bad_input_and_truncates_over_budget() {
        let server = test_server();
        let denied = TestRunTool::invoke(
            &server,
            TestRunArgs {
                checks: Some(vec!["scene_read".to_owned(), "shell".to_owned()]),
                budget_bytes: None,
            },
        )
        .expect_err("unknown check refuses");
        assert_eq!(denied.code, "unknown_check");
        assert!(denied.message.contains("scene_read"));
        assert!(denied.message.contains("log_digest"));
        let empty = run_checks(
            &server,
            &TestRunArgs {
                checks: Some(Vec::new()),
                budget_bytes: None,
            },
        )
        .expect_err("empty refuses");
        assert_eq!(empty.code, "empty_checks");
        for budget in [0, TEST_RUN_MAX_BUDGET + 1] {
            let bad = run_checks(
                &server,
                &TestRunArgs {
                    checks: None,
                    budget_bytes: Some(budget),
                },
            )
            .expect_err("bad budget refuses");
            assert_eq!(bad.code, "bad_budget", "budget {budget}");
            assert!(bad.message.contains(&TEST_RUN_MAX_BUDGET.to_string()));
        }
        let many = vec!["scene_read".to_owned(); MAX_TEST_RUN_CHECKS + 1];
        let overflow = run_checks(
            &server,
            &TestRunArgs {
                checks: Some(many),
                budget_bytes: None,
            },
        )
        .expect_err("over-long refuses");
        assert_eq!(overflow.code, "too_many_checks");
        // A tiny detail budget cuts trailing cases and says so.
        let cut = run_checks(
            &server,
            &TestRunArgs {
                checks: None,
                budget_bytes: Some(8),
            },
        )
        .expect("tiny budget still serves");
        assert!(cut.truncated, "tiny budget truncates");
        assert!(
            cut.results.len() < TEST_RUN_CHECKS.len(),
            "trailing cases cut"
        );
        // The failed-case shape stays structured: code plus message.
        let failed = case_failed(
            "tool_budget",
            &McpToolError::new("over_budget", "list costs 1 chars, budget is 0"),
        );
        assert!(!failed.ok);
        assert!(failed.detail.contains("over_budget"));
    }
}
